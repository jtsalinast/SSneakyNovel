// splitMultiField parses a comma-separated multi-value field (the wire format
// shared with the frontend for conflict_scale / protagonist_type, which now
// accept several picks). Empty parts are dropped and values are trimmed;
// the result preserves order and removes case-insensitive duplicates.
func splitMultiField(v string) []string {
	out := []string{}
	seen := map[string]bool{}
	for _, p := range strings.Split(v, ",") {
		p = strings.TrimSpace(p)
		if p == "" {
			continue
		}
		k := strings.ToLower(p)
		if seen[k] {
			continue
		}
		seen[k] = true
		out = append(out, p)
	}
	return out
}

// effectiveMulti resolves a stored comma-separated multi-select field: each
// "other" entry is replaced by the custom text (when present), empties and
// duplicates are dropped, and order is preserved. Works for both
// conflict_scale/conflict_other and protagonist_type/protagonist_other.
func effectiveMulti(stored, custom string) string {
	vals := []string{}
	for _, v := range splitMultiField(stored) {
		if v == "other" {
			if c := strings.TrimSpace(custom); c != "" {
				vals = append(vals, c)
			}
			continue
		}
		vals = append(vals, v)
	}
	if strings.TrimSpace(stored) == "" {
		if c := strings.TrimSpace(custom); c != "" {
			vals = append(vals, c)
		}
	}
	return strings.Join(vals, ", ")
}

// EffectiveConflict returns the conflict scale(s), resolving every "other"
// option against ConflictOther. Multi-value aware: the stored field may hold
// a comma-separated list of picks.
func (s *StoryConfig) EffectiveConflict() string {
	return effectiveMulti(s.ConflictScale, s.ConflictOther)
}

// EffectiveProtagonist returns the protagonist type(s), resolving every
// "other" option against ProtagonistOther. Multi-value aware.
func (s *StoryConfig) EffectiveProtagonist() string {
	return effectiveMulti(s.ProtagonistType, s.ProtagonistOther)
}

// EffectiveMotif returns the literary motif. When the dedicated Motif field is
// empty it falls back to Theme (legacy configs stored both merged in one
// field), so prompts never lose the motif information entirely.
func (s *StoryConfig) EffectiveMotif() string {
	if m := strings.TrimSpace(s.Motif); m != "" {
		return m
	}
	return strings.TrimSpace(s.Theme)
}

// —— Story output language (EN / ES) —
//
// OutputLanguage lets the author pin the language of every AI-generated text
// (story idea, sections, outline, prose). Valid values: "en", "es"; empty
// means "follow the project Language" (zh/en), i.e. legacy behavior.

// NormalizeOutputLanguage maps any accepted spelling to "en"/"es"; unknown or
// empty values return "" (= follow the project language).
func NormalizeOutputLanguage(v string) string {
	switch strings.ToLower(strings.TrimSpace(v)) {
	case "en", "english", "inglés", "ingles":
		return "en"
	case "es", "spanish", "español", "espanol", "castellano":
		return "es"
	default:
		return ""
	}
}

// OutputLanguageName returns the display name for a story output language key.
func OutputLanguageName(key string) string {
	switch NormalizeOutputLanguage(key) {
	case "en":
		return "English"
	case "es":
		return "Español"
	}
	return ""
}

// EffectiveOutputLanguage resolves the story's pinned output language from a
// full config: "en"/"es" when set; otherwise "" meaning the prompts should
// keep following the project Language as before.
func EffectiveOutputLanguage(cfg *Config) string {
	if cfg == nil {
		return ""
	}
	return NormalizeOutputLanguage(cfg.Story.OutputLanguage)
}

